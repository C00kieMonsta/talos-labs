// Turns brand/mineral/icons/*.svg into src/components/icons/<Name>Icon.tsx, plus the spiral mark and an index.
// Run from apps/desktop: pnpm exec tsx scripts/gen-icons.ts
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const iconDir = resolve(root, "brand/mineral/icons");
const outDir = resolve(root, "src/components/icons");
mkdirSync(outDir, { recursive: true });

const pascal = (slug: string) => slug.split("-").map((part) => part[0]!.toUpperCase() + part.slice(1)).join("");

/** The children of the root <svg>, with attribute names camel-cased for JSX. */
function inner(svg: string): string {
  const open = svg.indexOf(">") + 1;
  const close = svg.lastIndexOf("</svg>");
  return svg
    .slice(open, close)
    .trim()
    .replace(/\s+(\w+)-(\w+)=/g, (_, a: string, b: string) => ` ${a}${b[0]!.toUpperCase()}${b.slice(1)}=`)
    .replace(/></g, ">\n      <");
}

function component(name: string, body: string, doc: string): string {
  return `${doc}\nimport type { KitIconProps } from "../KitIcon";\nimport { KitIcon } from "../KitIcon";\n\nexport function ${name}(props: KitIconProps) {\n  return (\n    <KitIcon {...props}>\n      ${body}\n    </KitIcon>\n  );\n}\n`;
}

const header = "// Generated by scripts/gen-icons.ts from brand/mineral. Do not edit by hand.";
const names: string[] = [];
for (const file of readdirSync(iconDir).filter((f) => f.endsWith(".svg")).sort()) {
  const slug = basename(file, ".svg");
  const name = `${pascal(slug)}Icon`;
  names.push(name);
  writeFileSync(resolve(outDir, `${name}.tsx`), component(name, inner(readFileSync(resolve(iconDir, file), "utf8")), `${header}\n// Source: brand/mineral/icons/${file}`));
}

// The spiral mark: one geometry for all three kit colourways, so the colour comes from currentColor.
const spiral = readFileSync(resolve(root, "brand/mineral/logos/spiral-mark-dark.svg"), "utf8");
const d = /\bd="([^"]+)"/.exec(spiral)?.[1];
if (d === undefined) throw new Error("spiral path not found");
writeFileSync(
  resolve(outDir, "SpiralMark.tsx"),
  `${header}\n// Source: brand/mineral/logos/spiral-mark-dark.svg (light and rust share the geometry).\nimport type { SVGProps } from "react";\n\nconst PATH =\n  "${d}";\n\n/** The Talos Labs spiral in currentColor, drawn in a 100 x 100 box. */\nexport function SpiralMark({ size = 24, ...rest }: Omit<SVGProps<SVGSVGElement>, "ref"> & { size?: number | string }) {\n  return (\n    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 100 100" fill="none" {...rest}>\n      <path d={PATH} stroke="currentColor" strokeWidth="1.45" strokeLinecap="round" strokeLinejoin="round" />\n      <circle cx="50" cy="50" r="1.4" fill="currentColor" />\n    </svg>\n  );\n}\n`,
);

const index = [header, ...names.map((n) => `export { ${n} } from "./${n}";`), `export { SpiralMark } from "./SpiralMark";`, "", `/** Every generated kit icon component name, for the icons test. */`, `export const KIT_ICON_NAMES: readonly string[] = [${names.map((n) => `"${n}"`).join(", ")}];`, ""].join("\n");
writeFileSync(resolve(outDir, "index.ts"), index);
console.log(`${names.length} icons + SpiralMark written to src/components/icons`);
